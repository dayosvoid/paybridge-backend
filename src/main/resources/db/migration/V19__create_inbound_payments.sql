-- Money received from the remittance provider (USD for a customer's account number).
-- provider_reference is unique, so a webhook delivered twice can never credit twice.
-- UNMATCHED and FAILED rows are the operator's list of payments that need attention.
CREATE TABLE inbound_payments (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference          VARCHAR(255) NOT NULL,
    provider_reference VARCHAR(255) NOT NULL,
    account_number     VARCHAR(255) NOT NULL,
    currency           VARCHAR(255) NOT NULL,
    amount_minor       BIGINT       NOT NULL,
    sender_name        VARCHAR(255),
    status             VARCHAR(255) NOT NULL,
    failure_reason     VARCHAR(500),
    received_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    credited_at        TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uq_inbound_payments_reference UNIQUE (reference),
    CONSTRAINT uq_inbound_payments_provider_reference UNIQUE (provider_reference),
    CONSTRAINT inbound_payments_currency_check CHECK (currency IN ('NGN', 'USD')),
    CONSTRAINT inbound_payments_status_check CHECK (status IN ('RECEIVED', 'CREDITED', 'UNMATCHED', 'FAILED')),
    CONSTRAINT inbound_payments_amount_positive CHECK (amount_minor > 0)
);

CREATE INDEX idx_inbound_payments_status ON inbound_payments (status, id DESC);
