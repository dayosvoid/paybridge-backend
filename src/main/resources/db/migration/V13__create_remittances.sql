-- Remittances: a cross-currency payment (NGN -> USD) priced with a configured demo rate.
-- The two currencies are posted as two separate balanced ledger legs through the FX pool accounts,
-- so each currency balances on its own.
CREATE TABLE remittances (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference                 VARCHAR(255)   NOT NULL,
    idempotency_key           VARCHAR(255)   NOT NULL,
    source_account            VARCHAR(255)   NOT NULL,
    beneficiary_account       VARCHAR(255)   NOT NULL,
    source_currency           VARCHAR(255)   NOT NULL,
    destination_currency      VARCHAR(255)   NOT NULL,
    source_amount_minor       BIGINT         NOT NULL,
    destination_amount_minor  BIGINT         NOT NULL,
    fx_rate                   NUMERIC(19, 8) NOT NULL,
    rate_type                 VARCHAR(50)    NOT NULL,
    status                    VARCHAR(255)   NOT NULL,
    failure_reason            VARCHAR(500),
    created_at                TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    completed_at              TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uq_remittances_reference UNIQUE (reference),
    CONSTRAINT uq_remittances_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT remittances_source_currency_check CHECK (source_currency IN ('NGN', 'USD')),
    CONSTRAINT remittances_destination_currency_check CHECK (destination_currency IN ('NGN', 'USD')),
    CONSTRAINT remittances_currencies_differ CHECK (source_currency <> destination_currency),
    CONSTRAINT remittances_status_check CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED')),
    CONSTRAINT remittances_source_amount_positive CHECK (source_amount_minor > 0),
    CONSTRAINT remittances_destination_amount_positive CHECK (destination_amount_minor > 0),
    CONSTRAINT remittances_rate_positive CHECK (fx_rate > 0)
);

CREATE INDEX idx_remittances_source_account ON remittances (source_account, id);
