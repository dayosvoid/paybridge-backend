-- Sending money abroad through a remittance provider.
-- provider_quotes: every provider's offer, stored until it expires so the customer can pick one.
-- outbound_remittances: one row per payment. quote_id is unique, so a quote is sent at most once.
CREATE TABLE provider_quotes (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_id                 VARCHAR(255)   NOT NULL,
    provider_id              VARCHAR(255)   NOT NULL,
    source_account           VARCHAR(255)   NOT NULL,
    source_amount_minor      BIGINT         NOT NULL,
    fee_minor                BIGINT         NOT NULL,
    destination_currency     VARCHAR(255)   NOT NULL,
    destination_amount_minor BIGINT         NOT NULL,
    fx_rate                  NUMERIC(19, 8) NOT NULL,
    eta_minutes              INTEGER        NOT NULL,
    created_at               TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at               TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_provider_quotes_quote_id UNIQUE (quote_id),
    CONSTRAINT provider_quotes_destination_currency_check CHECK (destination_currency IN ('NGN', 'USD')),
    CONSTRAINT provider_quotes_source_amount_positive CHECK (source_amount_minor > 0),
    CONSTRAINT provider_quotes_fee_non_negative CHECK (fee_minor >= 0),
    CONSTRAINT provider_quotes_destination_amount_positive CHECK (destination_amount_minor > 0),
    CONSTRAINT provider_quotes_rate_positive CHECK (fx_rate > 0)
);

CREATE TABLE outbound_remittances (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference                VARCHAR(255)   NOT NULL,
    idempotency_key          VARCHAR(255)   NOT NULL,
    quote_id                 VARCHAR(255)   NOT NULL,
    provider_id              VARCHAR(255)   NOT NULL,
    provider_reference       VARCHAR(255),
    source_account           VARCHAR(255)   NOT NULL,
    source_amount_minor      BIGINT         NOT NULL,
    fee_minor                BIGINT         NOT NULL,
    destination_currency     VARCHAR(255)   NOT NULL,
    destination_amount_minor BIGINT         NOT NULL,
    fx_rate                  NUMERIC(19, 8) NOT NULL,
    beneficiary_name         VARCHAR(255)   NOT NULL,
    beneficiary_account      VARCHAR(255)   NOT NULL,
    beneficiary_bank         VARCHAR(255),
    status                   VARCHAR(255)   NOT NULL,
    failure_reason           VARCHAR(500),
    created_at               TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    completed_at             TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uq_outbound_remittances_reference UNIQUE (reference),
    CONSTRAINT uq_outbound_remittances_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT uq_outbound_remittances_quote_id UNIQUE (quote_id),
    CONSTRAINT fk_outbound_remittances_quote FOREIGN KEY (quote_id) REFERENCES provider_quotes (quote_id),
    CONSTRAINT outbound_remittances_status_check CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED')),
    CONSTRAINT outbound_remittances_source_amount_positive CHECK (source_amount_minor > 0),
    CONSTRAINT outbound_remittances_fee_non_negative CHECK (fee_minor >= 0)
);

CREATE INDEX idx_outbound_remittances_pending ON outbound_remittances (created_at) WHERE status = 'PENDING';
CREATE INDEX idx_outbound_remittances_source ON outbound_remittances (source_account, id);
