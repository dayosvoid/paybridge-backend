-- Settlement foundation.
--
-- 1. transfers.succeeded_at: when a transfer reached SUCCESS. Settlement eligibility is measured
--    from here, not from created_at, because a PENDING transfer can succeed hours after it was created.
-- 2. transfers.settlement_batch_reference: set once, inside the batch transaction, when the transfer
--    is included in a settlement batch. NULL means "not settled yet".
-- 3. settlement_batches / settlement_items: one batch per provider and currency, one item per transfer.

ALTER TABLE transfers ADD COLUMN succeeded_at TIMESTAMP(6) WITH TIME ZONE;
ALTER TABLE transfers ADD COLUMN settlement_batch_reference VARCHAR(255);

-- Best available time for transfers that succeeded before this migration.
UPDATE transfers SET succeeded_at = created_at WHERE status = 'SUCCESS' AND succeeded_at IS NULL;

ALTER TABLE transfers
    ADD CONSTRAINT transfers_succeeded_at_when_success
        CHECK (status <> 'SUCCESS' OR succeeded_at IS NOT NULL);

-- Finds the next settlement candidates without scanning every transfer.
CREATE INDEX idx_transfers_settlement_eligible
    ON transfers (succeeded_at, id)
    WHERE status = 'SUCCESS' AND bank_code IS NOT NULL AND settlement_batch_reference IS NULL;

-- POSTED     = PayBridge's own ledger posting for the batch was committed.
-- RECONCILED = the batch was compared with provider records and matched.
-- EXCEPTION  = the comparison found a problem. The ledger posting is never rolled back for this.
CREATE TABLE settlement_batches (
                                    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    reference    VARCHAR(255) NOT NULL,
                                    provider     VARCHAR(50)  NOT NULL,
                                    currency     VARCHAR(255) NOT NULL,
                                    status       VARCHAR(255) NOT NULL,
                                    total_minor  BIGINT       NOT NULL,
                                    item_count   INTEGER      NOT NULL,
                                    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
                                    version      BIGINT       NOT NULL DEFAULT 0,
                                    CONSTRAINT uq_settlement_batches_reference UNIQUE (reference),
                                    CONSTRAINT settlement_batches_currency_check CHECK (currency IN ('NGN', 'USD')),
                                    CONSTRAINT settlement_batches_status_check CHECK (status IN ('POSTED', 'RECONCILED', 'EXCEPTION')),
                                    CONSTRAINT settlement_batches_total_positive CHECK (total_minor > 0),
                                    CONSTRAINT settlement_batches_item_count_positive CHECK (item_count > 0)
);

CREATE TABLE settlement_items (
                                  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  batch_id           BIGINT       NOT NULL,
                                  transfer_reference VARCHAR(255) NOT NULL,
                                  amount_minor       BIGINT       NOT NULL,
                                  currency           VARCHAR(255) NOT NULL,
                                  created_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    -- A transfer can enter settlement exactly once.
                                  CONSTRAINT uq_settlement_items_transfer_reference UNIQUE (transfer_reference),
                                  CONSTRAINT fk_settlement_items_batch FOREIGN KEY (batch_id) REFERENCES settlement_batches (id),
                                  CONSTRAINT fk_settlement_items_transfer FOREIGN KEY (transfer_reference) REFERENCES transfers (reference),
                                  CONSTRAINT settlement_items_amount_positive CHECK (amount_minor > 0),
                                  CONSTRAINT settlement_items_currency_check CHECK (currency IN ('NGN', 'USD'))
);

CREATE INDEX idx_settlement_items_batch ON settlement_items (batch_id);