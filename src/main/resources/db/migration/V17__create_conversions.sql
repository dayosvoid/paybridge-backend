-- PayBridge conversion tool: a customer converts between their own NGN and USD balances.
-- A quote is stored with an expiry; a conversion consumes one quote (quote_id is unique, so a quote
-- can be used once). The money moves as two balanced ledger legs through the FX pool accounts.
CREATE TABLE conversion_quotes (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_id                  VARCHAR(255)   NOT NULL,
    account_number            VARCHAR(255)   NOT NULL,
    source_currency           VARCHAR(255)   NOT NULL,
    destination_currency      VARCHAR(255)   NOT NULL,
    source_amount_minor       BIGINT         NOT NULL,
    destination_amount_minor  BIGINT         NOT NULL,
    fx_rate                   NUMERIC(19, 8) NOT NULL,
    rate_type                 VARCHAR(50)    NOT NULL,
    created_at                TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at                TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_conversion_quotes_quote_id UNIQUE (quote_id),
    CONSTRAINT conversion_quotes_source_currency_check CHECK (source_currency IN ('NGN', 'USD')),
    CONSTRAINT conversion_quotes_destination_currency_check CHECK (destination_currency IN ('NGN', 'USD')),
    CONSTRAINT conversion_quotes_currencies_differ CHECK (source_currency <> destination_currency),
    CONSTRAINT conversion_quotes_source_amount_positive CHECK (source_amount_minor > 0),
    CONSTRAINT conversion_quotes_destination_amount_positive CHECK (destination_amount_minor > 0),
    CONSTRAINT conversion_quotes_rate_positive CHECK (fx_rate > 0)
);

CREATE TABLE conversions (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference                 VARCHAR(255)   NOT NULL,
    idempotency_key           VARCHAR(255)   NOT NULL,
    quote_id                  VARCHAR(255)   NOT NULL,
    account_number            VARCHAR(255)   NOT NULL,
    source_currency           VARCHAR(255)   NOT NULL,
    destination_currency      VARCHAR(255)   NOT NULL,
    source_amount_minor       BIGINT         NOT NULL,
    destination_amount_minor  BIGINT         NOT NULL,
    fx_rate                   NUMERIC(19, 8) NOT NULL,
    rate_type                 VARCHAR(50)    NOT NULL,
    status                    VARCHAR(255)   NOT NULL,
    failure_reason            VARCHAR(500),
    created_at                TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    completed_at              TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uq_conversions_reference UNIQUE (reference),
    CONSTRAINT uq_conversions_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT uq_conversions_quote_id UNIQUE (quote_id),
    CONSTRAINT fk_conversions_quote FOREIGN KEY (quote_id) REFERENCES conversion_quotes (quote_id),
    CONSTRAINT conversions_status_check CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED')),
    CONSTRAINT conversions_currencies_differ CHECK (source_currency <> destination_currency)
);

CREATE INDEX idx_conversions_account ON conversions (account_number, id);
